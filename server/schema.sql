CREATE SCHEMA IF NOT EXISTS dog_discovery;
REVOKE ALL ON SCHEMA dog_discovery FROM PUBLIC;
SET LOCAL search_path TO dog_discovery, pg_catalog;
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_user_id UUID UNIQUE,
  name VARCHAR(80) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE CHECK(email=lower(email)),
  location VARCHAR(100) NOT NULL DEFAULT '', bio VARCHAR(1000) NOT NULL DEFAULT '',
  avatar TEXT, created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE TABLE IF NOT EXISTS images (
  id UUID PRIMARY KEY, owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  url TEXT NOT NULL UNIQUE, created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE TABLE IF NOT EXISTS dogs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INTEGER NOT NULL REFERENCES users(id), name VARCHAR(60) NOT NULL,
  breed VARCHAR(80) NOT NULL, age_months INTEGER NOT NULL CHECK(age_months BETWEEN 0 AND 360),
  size TEXT NOT NULL CHECK(size IN ('Small','Medium','Large')),
  sex TEXT NOT NULL CHECK(sex IN ('Female','Male')), location VARCHAR(100) NOT NULL,
  description TEXT NOT NULL, traits TEXT NOT NULL DEFAULT '[]',
  status TEXT NOT NULL DEFAULT 'available' CHECK(status IN ('available','paused','adopted')),
  created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE TABLE IF NOT EXISTS dog_images (
  dog_id INTEGER NOT NULL REFERENCES dogs(id) ON DELETE CASCADE,
  url TEXT NOT NULL, position INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(dog_id,url)
);
CREATE TABLE IF NOT EXISTS favorites (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  dog_id INTEGER NOT NULL REFERENCES dogs(id) ON DELETE CASCADE, PRIMARY KEY(user_id,dog_id)
);
CREATE TABLE IF NOT EXISTS adoptions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dog_id INTEGER NOT NULL REFERENCES dogs(id) ON DELETE CASCADE,
  applicant_id INTEGER NOT NULL REFERENCES users(id), note TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','accepted','rejected','withdrawn')),
  created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'), UNIQUE(dog_id,applicant_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS one_adoption_per_dog ON adoptions(dog_id) WHERE status='accepted';
CREATE TABLE IF NOT EXISTS conversations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dog_id INTEGER NOT NULL REFERENCES dogs(id) ON DELETE CASCADE,
  member_id INTEGER NOT NULL REFERENCES users(id), UNIQUE(dog_id,member_id)
);
CREATE TABLE IF NOT EXISTS messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id INTEGER NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  sender_id INTEGER NOT NULL REFERENCES users(id), body TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX IF NOT EXISTS dogs_owner ON dogs(owner_id);
CREATE INDEX IF NOT EXISTS dogs_status ON dogs(status);
CREATE INDEX IF NOT EXISTS adoption_applicant ON adoptions(applicant_id);
CREATE INDEX IF NOT EXISTS message_thread ON messages(conversation_id,id);
-- Application tables are private to the Express backend, not the public Data API.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE images ENABLE ROW LEVEL SECURITY;
ALTER TABLE dogs ENABLE ROW LEVEL SECURITY;
ALTER TABLE dog_images ENABLE ROW LEVEL SECURITY;
ALTER TABLE favorites ENABLE ROW LEVEL SECURITY;
ALTER TABLE adoptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA dog_discovery FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA dog_discovery FROM PUBLIC;
DO $$
DECLARE role_name text;
BEGIN
  FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA dog_discovery FROM %I',role_name);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA dog_discovery FROM %I',role_name);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA dog_discovery FROM %I',role_name);
    END IF;
  END LOOP;
END $$;
